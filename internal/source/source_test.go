package source

import "testing"

func TestVerCmp(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		{"0.3.0", "0.3.0", 0},
		{"v0.3.0", "0.3.0", 0},
		{"1.2.3", "1.2.3", 0},
		{"1.2.3", "1.2.4", -1},
		{"1.10.0", "1.9.9", 1},
		{"1.2", "1.2.0", -1},
		{"1.2.0", "1.2", 1},
		{"2.0.0", "1.0.0", 1},
		{"1.0.0-alpha", "1.0.0", -1},
		{"0.9.0", "3.0.0", -1},
		{"2.0.0", "1.99.99", 1},
		{"0.0.1", "0.0.0", 1},
		{"", "0.0.0", 1},
		{"v1.2.3", "1.2.2", 1},
		// Pre-release and post-release tags order around their release.
		{"0.5.3rc2", "0.5.23", -1},
		{"1.0.0rc1", "1.0.0", -1},
		{"1.0.0rc1", "1.0.0rc2", -1},
		{"1.0.0-rc.1", "1.0.0rc1", 0},
		{"1.0.0.dev1", "1.0.0a1", -1},
		{"1.0.0a1", "1.0.0b1", -1},
		{"1.0.0b2", "1.0.0rc1", -1},
		{"1.0.0", "1.0.0.post1", -1},
		{"0.3.4.post1", "0.3.5", -1},
		{"0.3.4.post1", "0.3.4.post2", -1},
		{"1.0.0-hotfix", "1.0.0", 1},
		{"1.2.3", "v1.2.03", 0},
		{"1.99999999999999999999", "1.99999999999999999998", 1},
	}
	for _, c := range cases {
		if got := VerCmp(c.a, c.b); got != c.want {
			t.Errorf("VerCmp(%q, %q) = %d, want %d", c.a, c.b, got, c.want)
		}
	}
}
